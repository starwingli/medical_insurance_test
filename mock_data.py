def get_cases() -> list[dict]:
    """返回用例的浅拷贝列表，避免调用方修改全局数据。"""
    return [c.copy() for c in MOCK_CASES]


def get_gold(case_id: str) -> dict:
    """按 case_id 取人工标注的六要素（不存在时返回全未提及）。"""
    for c in MOCK_CASES:
        if c["case_id"] == case_id:
            return dict(c["gold"])
    return {f: config.UNMENTIONED for f in config.SIX_FIELDS}


def self_check() -> list[str]:
    """
    自检：gold 里的原文摘录字段必须是原文连续片段、枚举字段必须命中闭集。
    返回问题描述列表（空列表 = 全部通过）。供测试/重构时快速校验数据一致性。
    """
    problems: list[str] = []
    for c in MOCK_CASES:
        cid, text, gold = c["case_id"], c["source_text"], c["gold"]
        if set(gold.keys()) != set(config.SIX_FIELDS):
            problems.append(f"{cid}: gold 字段不是六要素 {config.SIX_FIELDS}")
        for f in config.VERBATIM_FIELDS:
            v = gold[f]
            if v != config.UNMENTIONED and v not in text:
                problems.append(f"{cid}: gold[{f}]={v!r} 不是原文连续片段")
        for f in config.ENUM_FIELDS:
            v = gold[f]
            if v != config.UNMENTIONED and v not in config.ENUMS[f]:
                problems.append(f"{cid}: gold[{f}]={v!r} 不在枚举闭集内")
    return problems
